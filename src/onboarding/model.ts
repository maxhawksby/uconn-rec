// A fixture, never a directory lookup or an assertion about the supplied email.
export const DEMO_IDENTITY = { firstName: 'Alex', lastName: 'Morgan', source: 'demo' as const };
export type StudentProfile = {
  version: 1;
  email: string;
  identity: typeof DEMO_IDENTITY;
  preferredFirstName: string;
  year: typeof YEARS[number];
  interests: string[];
  completedAt: string;
};
export function normalizeEmail(value: string) { return value.trim().toLowerCase(); }
export function isUConnEmail(value: string) {
  return /^[a-z0-9]+(?:[._+\-][a-z0-9]+)*@uconn\.edu$/i.test(normalizeEmail(value));
}
export function isNamePreference(value: string) {
  const name = value.trim();
  // A format check, not proof that a name is real or appropriate.
  return name.length <= 40 && (!name || /^\p{L}[\p{L}\p{M}]*(?:[ '’\-][\p{L}\p{M}]+)*$/u.test(name));
}
export function firstName(profile: StudentProfile | null) { return profile?.preferredFirstName || profile?.identity.firstName || 'Husky'; }
export function fullName(profile: StudentProfile | null) { return profile ? `${firstName(profile)} ${profile.identity.lastName}` : 'Your Rec space'; }
export function initials(profile: StudentProfile | null) { return profile ? `${firstName(profile)[0]}${profile.identity.lastName[0]}`.toUpperCase() : 'U'; }
export function isStudentProfile(value: unknown): value is StudentProfile {
  if (!value || typeof value !== 'object') return false;
  const p = value as StudentProfile;
  return p.version === 1 && typeof p.email === 'string' && isUConnEmail(p.email)
    && p.identity?.source === 'demo' && p.identity.firstName === DEMO_IDENTITY.firstName && p.identity.lastName === DEMO_IDENTITY.lastName
    && typeof p.preferredFirstName === 'string' && isNamePreference(p.preferredFirstName)
    && YEARS.includes(p.year) && Array.isArray(p.interests) && p.interests.length > 0
    && new Set(p.interests).size === p.interests.length
    && p.interests.every(id => INTERESTS.some(x => x.id === id))
    && typeof p.completedAt === 'string' && Number.isFinite(Date.parse(p.completedAt));
}
export function suggestedCategories(profile: StudentProfile | null) {
  return new Set(INTERESTS.filter(x => profile?.interests.includes(x.id)).map(x => x.category).filter(Boolean));
}
