// Writes the catalog migrations from the app's own lists, so the server and the app agree:
// - schools (src/data/schools.ts), which gate sign-up
// - majors (src/data/majors.ts), the standard list every campus starts with
// Run after editing either list:  npm run gen:catalog
const fs = require('fs'); const path = require('path'); const ts = require('typescript'); const vm = require('vm');
function load(file) {
  const js = ts.transpileModule(fs.readFileSync(file, 'utf8'), { compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2022 } }).outputText;
  const sandbox = { exports: {}, require: () => ({}) }; vm.runInNewContext(js, sandbox); return sandbox.exports;
}
const sandbox = { exports: load('src/data/schools.ts') };
const q = s => `'${String(s).replace(/'/g, "''")}'`;
const rows = sandbox.exports.SCHOOLS.map(s =>
  `  (${q(s.id)}, ${q(s.name)}, ${q(s.shortName)}, array[${s.emailDomains.map(q).join(', ')}], ${q(s.city)}, ${q(s.state)}, ${s.isPilot})`);
const sql = `-- Generated by scripts/gen-catalog-sql.cjs from src/data/schools.ts. Do not edit by hand.
insert into public.schools (id, name, short_name, email_domains, city, state, is_pilot) values
${rows.join(',\n')}
on conflict (id) do update set name = excluded.name, short_name = excluded.short_name,
  email_domains = excluded.email_domains, city = excluded.city, state = excluded.state, is_pilot = excluded.is_pilot;
`;
const out = path.join('supabase', 'migrations', '20261011233200_schools.sql');
fs.writeFileSync(out, sql); console.log(`Wrote ${sandbox.exports.SCHOOLS.length} schools to ${out}`);

const majors = load('src/data/majors.ts').MAJORS;
const majorSql = `-- Generated by scripts/gen-catalog-sql.cjs from src/data/majors.ts. Do not edit by hand.
insert into public.orgs (id, school_id, kind, name) values
${majors.map(m => `  (${q(m.id)}, null, 'major', ${q(m.name)})`).join(',\n')}
on conflict (id) do update set name = excluded.name;
`;
const majorOut = path.join('supabase', 'migrations', '20261012020100_majors.sql');
fs.writeFileSync(majorOut, majorSql); console.log(`Wrote ${majors.length} majors to ${majorOut}`);
