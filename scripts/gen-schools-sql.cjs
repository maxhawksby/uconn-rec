// Writes the schools migration from src/data/schools.ts so the server's list (used to gate
// sign-up) matches the list the app searches. Run after editing schools.ts:
//   node scripts/gen-schools-sql.cjs
const fs = require('fs'); const path = require('path'); const ts = require('typescript'); const vm = require('vm');
const src = fs.readFileSync('src/data/schools.ts', 'utf8');
const js = ts.transpileModule(src, { compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2022 } }).outputText;
const sandbox = { exports: {}, require: () => ({}) }; vm.runInNewContext(js, sandbox);
const q = s => `'${String(s).replace(/'/g, "''")}'`;
const rows = sandbox.exports.SCHOOLS.map(s =>
  `  (${q(s.id)}, ${q(s.name)}, ${q(s.shortName)}, array[${s.emailDomains.map(q).join(', ')}], ${q(s.city)}, ${q(s.state)}, ${s.isPilot})`);
const sql = `-- Generated by scripts/gen-schools-sql.cjs from src/data/schools.ts. Do not edit by hand.
insert into public.schools (id, name, short_name, email_domains, city, state, is_pilot) values
${rows.join(',\n')}
on conflict (id) do update set name = excluded.name, short_name = excluded.short_name,
  email_domains = excluded.email_domains, city = excluded.city, state = excluded.state, is_pilot = excluded.is_pilot;
`;
const out = path.join('supabase', 'migrations', '20261011233200_schools.sql');
fs.writeFileSync(out, sql); console.log(`Wrote ${sandbox.exports.SCHOOLS.length} schools to ${out}`);
